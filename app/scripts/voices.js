// Finds your own voice recordings in assets/voices/ (e.g. pooh-1.m4a, pooh-2.mp3,
// piglet-1.wav) and writes src/audio/voiceFiles.ts so the game plays them.
// Runs automatically on `npm start`.
const fs = require('fs');
const path = require('path');

const IDS = ['pooh', 'piglet', 'tigger', 'rabbit', 'owl', 'eeyore', 'kanga', 'robin', 'small', 'bee', 'woozle', 'heffalump', 'roo', 'poohpiglet', 'relations'];
const dir = path.join(__dirname, '..', 'assets', 'voices');
const out = path.join(__dirname, '..', 'src', 'audio', 'voiceFiles.ts');

const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /\.(m4a|mp3|wav|aac)$/i.test(f)) : [];
const lines = [];
for (const id of IDS) {
  const mine = files.filter((f) => path.parse(f).name.toLowerCase().replace(/[-_ ]?\d+$/, '') === id).sort();
  if (mine.length) lines.push(`  ${id}: [${mine.map((f) => `require('../../assets/voices/${f}')`).join(', ')}],`);
}
fs.writeFileSync(out, `// Generated by scripts/voices.js from the files in assets/voices/. Don't edit by hand.
export const VOICE_FILES: Partial<Record<string, number[]>> = {
${lines.join('\n')}${lines.length ? '\n' : ''}};
`);
console.log(lines.length ? `Voices: using your recordings for ${lines.length} character(s)` : 'Voices: none recorded yet (characters play their tunes instead)');
