// Finds your own character pictures in assets/portraits/ and writes
// src/ui/portraitImages.ts so the app uses them. Runs automatically on `npm start`.
const fs = require('fs');
const path = require('path');

const IDS = ['pooh', 'piglet', 'tigger', 'rabbit', 'owl', 'eeyore', 'kanga', 'robin', 'small', 'bee', 'woozle', 'heffalump'];
const dir = path.join(__dirname, '..', 'assets', 'portraits');
const out = path.join(__dirname, '..', 'src', 'ui', 'portraitImages.ts');

const files = fs.existsSync(dir) ? fs.readdirSync(dir) : [];
const found = [];
for (const id of IDS) {
  const file = files.find((f) => /\.(png|jpe?g|webp)$/i.test(f) && path.parse(f).name.toLowerCase() === id);
  if (file) found.push([id, file]);
}

const lines = found.map(([id, file]) => `  ${id}: require('../../assets/portraits/${file}'),`);
fs.writeFileSync(out, `// Generated by scripts/portraits.js from the files in assets/portraits/. Don't edit by hand.
import { ImageSourcePropType } from 'react-native';

export const PORTRAIT_IMAGES: Partial<Record<string, ImageSourcePropType>> = {
${lines.join('\n')}${lines.length ? '\n' : ''}};
`);
console.log(found.length ? `Portraits: using your pictures for ${found.map(([id]) => id).join(', ')}` : 'Portraits: using the drawn ones (no pictures in assets/portraits/)');
